// Prepares the hosted demonstration: generates secrets once and renders the Keycloak realm.
// Usage: DEMO_ORIGIN=https://demo.example.com AUTH_ORIGIN=https://auth.example.com bun deploy/hosted/prepare.ts
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const here = dirname(new URL(import.meta.url).pathname);
const envPath = resolve(here, '.env');
const realmSource = resolve(here, '../../infra/keycloak/jungle-realm.json');
const realmTarget = resolve(here, 'generated/jungle-realm.json');

const secret = () => randomBytes(24).toString('base64url');
const parseEnv = (text: string) =>
  Object.fromEntries(
    text
      .split('\n')
      .filter((line) => /^[A-Z0-9_]+=/.test(line))
      .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]),
  );
const existing: Record<string, string> = existsSync(envPath)
  ? parseEnv(readFileSync(envPath, 'utf8'))
  : {};
const origin = (key: string) => {
  const value = process.env[key] ?? existing[key];
  if (!value) throw new Error(`${key} is required (for example https://demo.example.com)`);
  const url = new URL(value);
  if (url.protocol !== 'https:' || url.pathname !== '/' || url.search || url.hash)
    throw new Error(`${key} must be a bare https origin`);
  return url.origin;
};
const env: Record<string, string> = {
  DEMO_ORIGIN: origin('DEMO_ORIGIN'),
  AUTH_ORIGIN: origin('AUTH_ORIGIN'),
  CADDY_GLOBAL_OPTIONS: process.env.CADDY_GLOBAL_OPTIONS ?? existing.CADDY_GLOBAL_OPTIONS ?? '',
};
// Secrets are generated once and preserved; none of them reuse the local demo credentials.
for (const key of [
  'POSTGRES_PASSWORD',
  'RUNTIME_DB_PASSWORD',
  'KEYCLOAK_ADMIN_PASSWORD',
  'PROVIDER_A_SECRET',
  'PROVIDER_B_SECRET',
  'VIEWER_PASSWORD',
  'OPERATOR_PASSWORD',
  'DEMO_OPERATOR_PASSWORD',
])
  env[key] = existing[key] || secret();
if (new URL(env.DEMO_ORIGIN).host === new URL(env.AUTH_ORIGIN).host)
  throw new Error('DEMO_ORIGIN and AUTH_ORIGIN must use different hosts');

const realm = JSON.parse(readFileSync(realmSource, 'utf8'));
realm.sslRequired = 'all';
realm.registrationAllowed = false;
realm.bruteForceProtected = true;
realm.failureFactor = 10;
for (const client of realm.clients) {
  if (client.clientId === 'jungle-console') {
    client.redirectUris = [`${env.DEMO_ORIGIN}/*`];
    client.webOrigins = [env.DEMO_ORIGIN];
  }
  if (client.clientId === 'provider-a') client.secret = env.PROVIDER_A_SECRET;
  if (client.clientId === 'provider-b') client.secret = env.PROVIDER_B_SECRET;
}
const passwords: Record<string, string> = {
  viewer: env.VIEWER_PASSWORD,
  operator: env.OPERATOR_PASSWORD,
  'demo-operator': env.DEMO_OPERATOR_PASSWORD,
};
for (const user of realm.users) {
  const password = passwords[user.username];
  if (!password) throw new Error(`No hosted password for realm user ${user.username}`);
  user.credentials = [{ type: 'password', value: password, temporary: false }];
}
const serialized = JSON.stringify(realm);
if (/demo-only/.test(serialized))
  throw new Error('Rendered realm still contains local credentials');

mkdirSync(dirname(realmTarget), { recursive: true });
writeFileSync(realmTarget, JSON.stringify(realm, null, 2) + '\n', { mode: 0o600 });
writeFileSync(
  envPath,
  '# Generated by deploy/hosted/prepare.ts. Private: never commit or share this file.\n' +
    Object.entries(env)
      .map(([key, value]) => `${key}=${value}`)
      .join('\n') +
    '\n',
  { mode: 0o600 },
);
console.log(`Wrote ${envPath} and ${realmTarget}`);
console.log(
  `Console: ${env.DEMO_ORIGIN} · users viewer, operator, demo-operator (passwords in .env)`,
);
