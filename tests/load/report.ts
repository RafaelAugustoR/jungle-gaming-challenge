import type { collectEnvironment, LoadRun } from './runner';

type Environment = Awaited<ReturnType<typeof collectEnvironment>>;
const value = (n: number | null | undefined, digits = 0) =>
  n === null || n === undefined ? '—' : n.toFixed(digits);

/** Raw comparison only: interpretation of bottlenecks belongs to the evidence write-up. */
export function renderReport(environment: Environment, runs: LoadRun[]) {
  const rows = runs.map((run) => {
    const s = run.summary;
    const o = s.outcomes;
    return `| ${run.scenario} | ${run.rate} | ${run.instances} | ${value(s.offeredRps, 1)} | ${s.issued} | ${s.notIssued} | ${value(s.completedRps, 1)} | ${value(s.financialRps, 1)} | ${o.processed} | ${o.rejected} | ${o.replay} | ${s.errors} | ${value(s.latencyMs.p50)} | ${value(s.latencyMs.p95)} | ${value(s.latencyMs.p99)} | ${value(s.intendedLatencyMs.p99)} | ${value(s.scheduleLagMs.p99)} | ${s.drainAfterWindowMs} |`;
  });
  const contention = runs.map((run) => {
    const d = run.database;
    return `| ${run.scenario} | ${run.rate} | ${run.instances} | ${value(d.lockWaitingBackends.mean, 2)} | ${value(d.lockWaitingBackends.max)} | ${value(d.oldestLockWaitMs.max)} | ${value(run.processMetrics?.walletLockConflicts)} | ${value(run.processMetrics?.financialRetries)} | ${value(d.outboxPending.max)} | ${value(d.outboxOldestAgeMs.p95)} | ${value(d.outboxOldestAgeMs.max)} | ${run.outboxDrain.drainedAfterMs === null ? `not drained (${run.outboxDrain.pendingWhenStopped} left)` : run.outboxDrain.drainedAfterMs} | ${value(run.outboxDrain.publishedPerSecondWhileDraining, 1)} |`;
  });
  const checks = runs.map((run) => {
    const v = run.verification;
    const head = `| ${run.scenario} | ${run.rate} | ${run.instances} |`;
    if (!v.completed)
      return `${head} — | — | — | — | — | HARNESS FAILED: ${v.error.split('\n')[0]} |`;
    const failed = Object.entries(v.checks)
      .filter(([, ok]) => !ok)
      .map(([name]) => name);
    const f = v.finalStates;
    return `${head} ${v.reconciliation.consistent}/${v.reconciliation.wallets} | ${f.PROCESSED} | ${f.REJECTED} | ${f.NOT_APPLIED} | ${v.readBackAfterUncertainResponse} | ${failed.length ? `FAILED: ${failed.join(', ')}` : 'ok'} |`;
  });
  const g = environment.generator.options;
  return `# Load test report

Generated by \`bun run test:load\` at ${environment.at} (commit ${environment.commit?.slice(0, 12)}${environment.dirtyWorkingTree ? ', dirty tree' : ''}).

## Environment

- Host: ${environment.cpu.model}, ${environment.cpu.logicalCores} logical cores, ${environment.memoryGiB} GiB RAM, ${environment.os.platform} ${environment.os.release}.
- Bun ${environment.bun}; images: ${environment.images.join(', ')}.
- PostgreSQL: ${String(environment.postgres.version).split(',')[0]}; max_connections=${environment.postgres.max_connections}; shared_buffers=${environment.postgres.shared_buffers}.
- Pool per API process: max ${environment.application.poolPerProcess.max}; lock timeout ${environment.application.financialLockTimeoutMs} ms; statement timeout ${environment.application.financialStatementTimeoutMs} ms.
- Generator: ${environment.generator.model}; ${environment.generator.distribution}.
- Options: warmup ${g.warmupS}s, measured ${g.durationS}s, seed ${g.seed}, wallets ${g.wallets}, opening ${g.openingCents}, oversized BET ratio ${g.oversizedRatio}, duplicate ratio ${g.duplicateRatio}, max in-flight ${g.maxInFlight}, request timeout ${g.requestTimeoutMs} ms.
- ${environment.note}

## Throughput and latency (measured window, warmup excluded)

Rates in operations/s; latency in ms from send to response; *Intended p99* is measured from the scheduled instant and exposes generator/backlog delay that send-to-response latency hides. "Financial" counts first submissions that reached a terminal business result (processed + rejected); replays are counted separately. "Errors" is every issued request without a business result: 5xx, unexpected 4xx, 409 conflicts, 202 pending and transport failures or timeouts (the same definition as the error rate).

| Scenario | Rate | APIs | Offered | Issued | Not issued | Completed/s | Financial/s | Processed | Rejected | Replays | Errors | p50 | p95 | p99 | Intended p99 | Sched. lag p99 | Drain after window |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## Contention and outbox lag

Lock waits are sampled from \`pg_stat_activity\` (backends waiting on a heavyweight lock). Conflicts and retries are per-process counters (\`wallet_lock_conflicts_total\`, \`jungle_retries_total{component="financial"}\`). Outbox drain is measured after the last response, up to the configured drain timeout; financial responses never wait for publication.

| Scenario | Rate | APIs | Lock waiters (mean) | Lock waiters (max) | Oldest lock wait ms | Lock conflicts | Financial retries | Outbox pending max | Outbox age p95 ms | Outbox age max ms | Outbox drain ms | Published/s while draining |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${contention.join('\n')}

## Reconciliation and invariants (whole run, warmup included)

Each run reconciles every wallet through the API against the balance expected from client-side results, and runs the shared ledger audit (\`tests/support/ledger-audit.ts\`: balanced pairs, no partial financial effects, exactly one receipt per transaction, no pending transaction, one event set per transaction).

| Scenario | Rate | APIs | Reconciled wallets | Processed | Rejected | Not applied | Read back | Invariants |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${checks.join('\n')}
`;
}
